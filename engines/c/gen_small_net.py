"""gen_small_net.py -- regenerates the small sorting-network block of logos_psort.c
(the section between the SMALLNET BEGIN and SMALLNET END markers).

Why generated: the networks are emitted as straight-line compare-exchanges. The same
reason as gen_avx2_leaf.py -- a loop form leaves gcc unrolling decisions in the way --
and here there is a second reason: one hand-written network per size from 4 to 16 is
about 400 compare-exchanges, which nobody should type or review by hand.

The network is Batcher odd-even mergesort, which is defined for any n (the generator
drops the comparators that fall outside the range). Every emitted network is verified
here by the 0-1 principle: a comparator network sorts all inputs if and only if it
sorts every sequence of zeros and ones, so 2^n binary inputs per size is a complete
proof, and the generator refuses to write a network that fails it.

The compare-exchange is written as one predicate and two selects rather than as
min/max, so that it moves elements and never duplicates one. That matters with a NaN
present: `y < x` is false, so the pair is left alone and the output stays a permutation
of the input's bit patterns, which is what logos_sort_f64 promises. A min/max pair
would return the same operand twice and LOSE the other.

Run from engines/c:  python gen_small_net.py
"""
import os
os.chdir(os.path.dirname(os.path.abspath(__file__)))

NL = chr(10)
LO, HI = 4, 16          # below 4, insertion sort is already straight-line and a call costs more than it saves


def batcher(n):
    """Batcher odd-even mergesort comparators for any n, in order."""
    pairs = []
    p = 1
    while p < n:
        k = p
        while k >= 1:
            for j in range(k % p, n - k, 2 * k):
                for i in range(min(k, n - j - k)):
                    if (i + j) // (p * 2) == (i + j + k) // (p * 2):
                        pairs.append((i + j, i + j + k))
            k //= 2
        p *= 2
    return pairs


def sorts_everything(n, pairs):
    """The 0-1 principle: sorting every binary sequence proves the network sorts everything."""
    for m in range(1 << n):
        v = [(m >> b) & 1 for b in range(n)]
        for i, j in pairs:
            if v[i] > v[j]:
                v[i], v[j] = v[j], v[i]
        if any(v[t] > v[t + 1] for t in range(n - 1)):
            return False
    return True


out = []
out.append("/* ---- SMALLNET BEGIN (generated by gen_small_net.py -- do not edit by hand) ----")
out.append(" * Branchless sorting networks for 4 to 16 elements, Batcher odd-even mergesort, straight-line.")
out.append(" * NET_CE moves elements (one predicate, two selects) instead of taking a min and a max, so a NaN")
out.append(" * leaves its pair alone and the output stays a permutation of the input's bit patterns.")
out.append(" * Each network is proved by the 0-1 principle in the generator before it is written here. */")
out.append("#define NET_CE(i, j) do { double x_ = a[i], y_ = a[j]; int c_ = (y_ < x_); \\")
out.append("                          a[i] = c_ ? y_ : x_; a[j] = c_ ? x_ : y_; } while (0)")
out.append("/* noinline on purpose: inlined into the dispatcher this would add spill slots to a frame that is")
out.append(" * stack-probed on EVERY call, which has cost this project a round before (see CLAUDE.md). */")
out.append("__attribute__((noinline)) static void net_sort_small(double *a, long n) {")
out.append("    switch (n) {")
counts = {}
for n in range(LO, HI + 1):
    pairs = batcher(n)
    assert sorts_everything(n, pairs), ("network does not sort", n)
    counts[n] = len(pairs)
    body = " ".join("NET_CE(%d,%d);" % (i, j) for i, j in pairs)
    # wrap at a readable width, indented under the case
    words, lines, cur = body.split(" "), [], ""
    for w in words:
        if len(cur) + len(w) + 1 > 112:
            lines.append(cur)
            cur = w
        else:
            cur = (cur + " " + w) if cur else w
    if cur:
        lines.append(cur)
    out.append("    case %d: %s" % (n, lines[0]))
    for ln in lines[1:]:
        out.append("            " + ln)
    out.append("            break;")
out.append("    default: break;   /* the caller checks the range; n outside it is a no-op, not a wrong sort */")
out.append("    }")
out.append("}")
out.append("/* comparators per size: " + ", ".join("%d:%d" % (n, counts[n]) for n in range(LO, HI + 1)) + " */")
out.append("/* ---- SMALLNET END ---- */")
block = NL.join(out) + NL

src = open("logos_psort.c", "rb").read().decode("utf-8")
b = "/* ---- SMALLNET BEGIN"
e = "/* ---- SMALLNET END ---- */" + NL
assert src.count(b) == 1 and src.count(e) == 1, "markers missing or duplicated in logos_psort.c"
i0 = src.index(b)
i1 = src.index(e) + len(e)
open("logos_psort.c", "wb").write((src[:i0] + block + src[i1:]).encode("utf-8"))
print("wrote %d networks (%d comparators total)" % (HI - LO + 1, sum(counts.values())))
