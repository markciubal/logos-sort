/* slopebench.cpp -- how much dearer does ONE ELEMENT get as n grows?
 *
 * An outside review (2026-09-19) read a scaling exponent off two sizes through the cost per element c = t/n:
 *     t ~ n^p   gives   p = ln(T_hi / T_lo) / ln(n_hi / n_lo) = 1 + ln(c_hi / c_lo) / ln(n_hi / n_lo),
 * at 2M and 50M, and compared a buffered sort with a strict in-place one that way. The scale report has the same two
 * numbers in its rows, but on this box its rows are measured minutes apart and the machine's speed drifts by a multiple in
 * that time (CLAUDE.md, methodology 2), so a slope read off two rows carries the drift.
 *
 * Here the two sizes are measured the way this project measures everything else: ADJACENTLY, in pairs. One side of a pair
 * sorts one array of n_hi elements; the other sorts K = n_hi / n_lo arrays of n_lo elements, generated by the same shape
 * generator at the small size, back to back. Both sides move exactly the same number of elements through the same work
 * buffer, so the ratio of the two times IS c_hi / c_lo. Which side goes first alternates, and the median over the pairs is
 * reported with its p10 and p90. Every contender is verified on both sizes before it is timed (ascending under '<' and an
 * order-independent hash of the bit patterns against the input's).
 *
 * std::sort is here as the calibration: by comparison count alone its growth from 2M to 50M is log2(50M) / log2(2M) =
 * 1.222, p = 1.062, and the memory hierarchy can only add to that. A harness that reads less than that for std::sort is
 * broken. The other calibration is the null: ./slopebench 8 50000000 50000000 puts the SAME size on both sides, so the
 * true growth is 0% and whatever it prints is this harness's error.
 *
 * PREDICTIONS, written before the first run (2026-09-20), growth of the cost per element from 2M to 50M:
 *   std::sort, 1 thread, uniform        +22% to +30%   (comparison count alone: +22.2%)
 *   logos buffered, 1 thread, uniform   +5% to +15%
 *   logos in-place, 1 thread, uniform   +10% to +25%   (the reviewed sibling line measured +9.0% for its own)
 *   logos, 14 threads                   -5% to +10%    (fixed costs amortise, bandwidth saturates: about flat)
 *   counting shapes, 1 thread           within 5% of zero;   the null: within 3% of zero
 * GRADES (two full runs, 8 pairs each; FINDINGS 3ae has the table):
 *   std::sort +23.5 / +22.3% (p 1.066 / 1.063)   RIGHT, and the calibration holds
 *   logos 1 thread +13.4 / +16.3%                 RIGHT on uniform; heavy_tail +17-19 is above the range
 *   in-place 1 thread +21.2 / +21.6%              RIGHT
 *   counting shapes -1.7 .. +0.5%, null -0.8 .. +2.0%     RIGHT
 *   14 threads                                    WRONG on six shapes of seven, in both directions: uniform +26-34% (2M doubles
 *       sit in the 24 MB last-level cache, 50M do not), the structured routes -31% to -60% (at 2M a parallel call on them is
 *       mostly fixed cost). One-thread cells reproduce within about 3 points, 14-thread cells within 10 to 17; one cell
 *       (block_perm in-place, 18 against 38) does not reproduce and is not evidence.
 *
 * Usage: ./slopebench [pairs] [n_lo] [n_hi] [shape]     defaults 8, 2000000, 50000000, every shape. LOGOS_THREADS=N. */
#include "logos_psort.h"
#include "bench_common.h"
#include <algorithm>
#include <chrono>
#include <cmath>
#include <cstdint>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <string>
#include <vector>

struct Rng { uint64_t s; uint64_t next() { s ^= s << 13; s ^= s >> 7; s ^= s << 17; return s; } double f() { return (double)(next() >> 11) / 9007199254740992.0; } };
static double nowms() { return std::chrono::duration<double, std::milli>(std::chrono::steady_clock::now().time_since_epoch()).count(); }
static void gen_blocks(double *a, size_t n, Rng &r, size_t nb) {
    if (nb > n) nb = n ? n : 1; size_t blk = (n + nb - 1) / nb; std::vector<size_t> perm(nb);
    for (size_t k = 0; k < nb; k++) perm[k] = k;
    for (size_t k = nb - 1; k > 0; k--) std::swap(perm[k], perm[r.next() % (k + 1)]);
    for (size_t i = 0; i < n; i++) a[i] = (double)perm[i / blk] * (double)blk + (double)(i % blk) + r.f() * 0.5;
}
/* the scale report's generators, written into a caller's buffer */
static void gen(const std::string &shape, double *a, size_t n, uint64_t seed) {
    Rng r{seed};
    if (shape == "uniform") for (size_t i = 0; i < n; i++) a[i] = r.f() * 2e9 - 1e9;
    else if (shape == "near_sorted") { for (size_t i = 0; i < n; i++) a[i] = (double)i; for (size_t k = 0; k < n / 100; k++) std::swap(a[r.next() % n], a[r.next() % n]); }
    else if (shape == "few_distinct") for (size_t i = 0; i < n; i++) a[i] = (double)(r.next() % 5) * 1e6;
    else if (shape == "heavy_tail") for (size_t i = 0; i < n; i++) a[i] = 1000.0 * std::pow(1.0 - r.f() * 0.999999, -1.0 / 1.2);
    else if (shape == "bimodal") for (size_t i = 0; i < n; i++) a[i] = ((r.next() & 1) ? 1e9 : -1e9) + r.f() * 10.0;
    else if (shape == "quantized") for (size_t i = 0; i < n; i++) a[i] = (double)(r.next() % 4096) / 64.0;
    else if (shape == "block_perm") gen_blocks(a, n, r, 64);
}
static inline uint64_t mix(uint64_t x) { x ^= x >> 30; x *= 0xbf58476d1ce4e5b9ULL; x ^= x >> 27; x *= 0x94d049bb133111ebULL; x ^= x >> 31; return x; }
static uint64_t mhash(const double *a, size_t n) { uint64_t s = 0; for (size_t i = 0; i < n; i++) { uint64_t b; memcpy(&b, &a[i], 8); s += mix(b); } return s; }
static bool ascending(const double *a, size_t n) { for (size_t i = 1; i < n; i++) if (a[i] < a[i - 1]) return false; return true; }

typedef void (*sort_fn)(double *, size_t, int);
static void s_std(double *a, size_t n, int) { std::sort(a, a + n); }
static void s_logos(double *a, size_t n, int t) { logos_sort_f64(a, n, t); }
static void s_inplace(double *a, size_t n, int t) { logos_sort_f64_inplace(a, n, t); }
struct Contender { const char *name; sort_fn f; int threads; };

int main(int argc, char **argv) {
    int pairs = argc > 1 ? atoi(argv[1]) : 8; if (pairs < 2) pairs = 2;
    size_t n_lo = argc > 2 ? (size_t)atof(argv[2]) : 2000000, n_hi = argc > 3 ? (size_t)atof(argv[3]) : 50000000;
    const char *only = argc > 4 ? argv[4] : NULL;
    if (n_lo < 1000 || n_hi < n_lo) { fprintf(stderr, "need 1000 <= n_lo <= n_hi\n"); return 2; }
    size_t K = n_hi / n_lo, n_small = K * n_lo;
    int P = bench_threads(logos_num_cpus());
    const Contender C[] = { { "std::sort", s_std, 1 }, { "logos", s_logos, 1 }, { "logos in-place", s_inplace, 1 }, { "logos", s_logos, P }, { "logos in-place", s_inplace, P } };
    const char *shapes[] = { "uniform", "heavy_tail", "bimodal", "near_sorted", "few_distinct", "quantized", "block_perm" };
    printf("cost per element at n_hi = %zu against n_lo = %zu (%zu small sorts per large one), %d pairs, sides alternate\n", n_hi, n_lo, K, pairs);
    printf("growth = c_hi / c_lo - 1, median of the pairs with p10..p90;  p = 1 + ln(c_hi / c_lo) / ln(n_hi / n_lo).  threads: 1 and %d\n", P);
    if (n_lo == n_hi) printf("NULL TEST: the same size on both sides, so the true growth is 0%% and what is printed is the error of this harness\n");
    printf("\n  %-13s %-15s %3s | %9s %9s | %-27s | %6s\n", "shape", "sort", "T", "ns/el lo", "ns/el hi", "growth (p10 .. p90)", "p");
    std::vector<double> big(n_hi), small(n_small), work(n_hi), g((size_t)pairs), clo((size_t)pairs), chi((size_t)pairs);
    int bad = 0;
    for (const char *sh : shapes) {
        if (only && strcmp(only, sh)) continue;
        gen(sh, big.data(), n_hi, 7);
        for (size_t k = 0; k < K; k++) gen(sh, small.data() + k * n_lo, n_lo, 100 + k);
        uint64_t hbig = mhash(big.data(), n_hi); std::vector<uint64_t> hs(K); for (size_t k = 0; k < K; k++) hs[k] = mhash(small.data() + k * n_lo, n_lo);
        for (const Contender &c : C) {
            /* verify before timing; this pass also warms the pools at both sizes */
            bool ok = true;
            memcpy(work.data(), big.data(), n_hi * 8); c.f(work.data(), n_hi, c.threads);
            if (!ascending(work.data(), n_hi) || mhash(work.data(), n_hi) != hbig) ok = false;
            memcpy(work.data(), small.data(), n_small * 8);
            for (size_t k = 0; k < K; k++) { double *w = work.data() + k * n_lo; c.f(w, n_lo, c.threads); if (!ascending(w, n_lo) || mhash(w, n_lo) != hs[k]) ok = false; }
            if (!ok) { printf("  %-13s %-15s %3d | VERIFY FAILED, not timed\n", sh, c.name, c.threads); bad++; continue; }
            for (int i = 0; i < pairs; i++) {
                double thi = 0, tlo = 0;
                for (int side = 0; side < 2; side++) {
                    bool hi = ((i & 1) != 0) == (side != 0);                  /* even pairs: large first; odd pairs: small first */
                    if (hi) { memcpy(work.data(), big.data(), n_hi * 8); double s = nowms(); c.f(work.data(), n_hi, c.threads); thi = nowms() - s; }
                    else { memcpy(work.data(), small.data(), n_small * 8); double s = nowms(); for (size_t k = 0; k < K; k++) c.f(work.data() + k * n_lo, n_lo, c.threads); tlo = nowms() - s; }
                }
                chi[(size_t)i] = thi * 1e6 / (double)n_hi; clo[(size_t)i] = tlo * 1e6 / (double)n_small; g[(size_t)i] = chi[(size_t)i] / clo[(size_t)i];
            }
            std::sort(g.begin(), g.end()); std::sort(clo.begin(), clo.end()); std::sort(chi.begin(), chi.end());
            auto med = [&](const std::vector<double> &v) { size_t m = v.size(); return (m & 1) ? v[m / 2] : 0.5 * (v[m / 2 - 1] + v[m / 2]); };
            double gm = med(g), g10 = g[(size_t)(0.10 * pairs)], g90 = g[(size_t)(0.90 * pairs)];
            double p = n_hi > n_lo ? 1.0 + std::log(gm) / std::log((double)n_hi / (double)n_lo) : 1.0;
            char cell[64]; snprintf(cell, sizeof cell, "%+6.1f%% (%+6.1f .. %+6.1f)", (gm - 1) * 100, (g10 - 1) * 100, (g90 - 1) * 100);
            printf("  %-13s %-15s %3d | %9.2f %9.2f | %-27s | %6.3f\n", sh, c.name, c.threads, med(clo), med(chi), cell, p);
            fflush(stdout);
        }
    }
    return bad ? 1 : 0;
}
