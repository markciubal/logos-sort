"""gen_nets.py -- writes src/kernel_nets.rs: the AVX2 kernel's bitonic sorting networks for up to
8, 16, 32 and 64 doubles as straight-line code (the Rust twin of engines/c/gen_avx2_leaf.py).
Run from anywhere:  python gen_nets.py
"""
import os

def sortvecs(K):
    out = [f"v{i} = sort1(v{i});" for i in range(K)]
    m = 2
    while m <= K:
        for b in range(0, K, m):
            for i in range(m // 4):
                x, y = b + m // 2 + i, b + m - 1 - i
                out.append(f"core::mem::swap(&mut v{x}, &mut v{y});")
            for i in range(m // 2):
                x = b + m // 2 + i
                out.append(f"v{x} = rev(v{x});")
            s = m // 2
            while s >= 1:
                for i in range(m):
                    if (i & s) == 0:
                        x, y = b + i, b + i + s
                        out.append(f"(v{x}, v{y}) = (_mm256_min_pd(v{x}, v{y}), _mm256_max_pd(v{x}, v{y}));")
                s >>= 1
            for i in range(m):
                out.append(f"v{b + i} = merge1(v{b + i});")
        m <<= 1
    return out

def netfn(K):
    n = 4 * K
    lines = [f"/// Sorts a[0..n), n <= {n}, no NaN. Generated by gen_nets.py: do not edit.",
             '#[target_feature(enable = "avx2")]',
             f"unsafe fn net{n}(a: *mut f64, n: usize) {{"]
    for i in range(K):
        lines.append(f"    let mut v{i} = ld(a, n, {i});")
    for s in sortvecs(K):
        lines.append("    " + s)
    for i in range(K):
        lines.append(f"    st(a, n, {i}, v{i});")
    lines.append("}")
    return "\n".join(lines) + "\n"

src = "// GENERATED by gen_nets.py -- bitonic networks over 2, 4, 8 and 16 vectors of four doubles.\n\n"
src += "".join(netfn(K) + "\n" for K in (2, 4, 8, 16))
path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "src", "kernel_nets.rs")
open(path, "wb").write(src.encode("utf-8"))
print("wrote", path, len(src), "bytes")
