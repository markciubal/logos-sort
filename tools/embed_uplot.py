#!/usr/bin/env python3
"""Turn the vendored uPlot into a C header, so scale-report.html stays ONE self-contained file.

The generated reports in this project are opened from disk and mailed around; none of them may
depend on a CDN or on a sibling file. uPlot is 50 KB, which is small enough to inline, so it is
vendored under engines/c/vendor/ and baked into the binary that writes the report.

Run:  python tools/embed_uplot.py        (regenerate after bumping the vendored version)
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VENDOR = os.path.join(ROOT, "engines", "c", "vendor")
OUT = os.path.join(ROOT, "engines", "c", "uplot_embed.h")
DELIM = "UPLOTEMBED"


def literal(name, path):
    with open(path, encoding="utf-8") as f:
        body = f.read()
    # A C++ raw string literal may not contain its own terminator.
    if ')' + DELIM + '"' in body:
        sys.exit("%s contains the raw-string terminator; pick another delimiter" % path)
    return 'static const char *const %s =\nR"%s(%s)%s";\n' % (name, DELIM, body, DELIM)


def main():
    js = os.path.join(VENDOR, "uplot.min.js")
    css = os.path.join(VENDOR, "uplot.min.css")
    for p in (js, css):
        if not os.path.exists(p):
            sys.exit("missing %s; see engines/c/vendor/README.md" % p)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* uplot_embed.h - GENERATED by tools/embed_uplot.py. Do not edit.\n"
                " * uPlot (MIT) vendored under engines/c/vendor/; see that directory's README\n"
                " * for the version and why it is inlined rather than fetched. */\n"
                "#ifndef LOGOS_UPLOT_EMBED_H\n#define LOGOS_UPLOT_EMBED_H\n\n")
        f.write(literal("UPLOT_JS", js))
        f.write("\n")
        f.write(literal("UPLOT_CSS", css))
        f.write("\n#endif\n")
    print("wrote %s (%d bytes)" % (OUT, os.path.getsize(OUT)))


if __name__ == "__main__":
    main()
